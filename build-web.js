// Builds the web app in docs/ (served by GitHub Pages; also opens straight from disk, no server needed).
// It bundles series.js and model.js unchanged so the browser runs the same tested code,
// embeds the weekly prices, and copies the report pages. Run after analyze.js and report.js: node build-web.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const assert = require('assert');
const here = (...p) => path.join(__dirname, ...p);
fs.mkdirSync(here('docs'), { recursive: true });

const src = f => fs.readFileSync(here(f), 'utf8');
const lib = `// Generated by build-web.js from series.js and model.js. Do not edit; edit those files and rebuild.
(function () {
  var modules = {
    './series': function (module, exports, require) {\n${src('series.js')}\n},
    './model': function (module, exports, require) {\n${src('model.js')}\n}
  }, cache = {};
  function require(name) {
    if (name === 'fs') return {}; // file reading is only used by the command-line scripts
    if (!cache[name]) { cache[name] = { exports: {} }; modules[name](cache[name], cache[name].exports, require); }
    return cache[name].exports;
  }
  (typeof window !== 'undefined' ? window : globalThis).D35 = Object.assign({}, require('./series'), require('./model'));
})();
`;
const data = `// Generated by build-web.js from out/weekly.json: weekly median potato price per district, [weekIndex, rupees per quintal].
(typeof window !== 'undefined' ? window : globalThis).WEEKLY = ${src('out/weekly.json')};
`;
fs.writeFileSync(here('docs', 'lib.js'), lib);
fs.writeFileSync(here('docs', 'data.js'), data);
for (const f of ['proof-of-work.html', 'farmer.html', 'NESFIC-D-35-Proof-of-Work.pdf']) fs.copyFileSync(here('out', f), here('docs', f));

// Self-check: the browser bundle must give the same forecast as the command-line analysis.
const box = vm.createContext({});
vm.runInContext(lib + data, box);
const f = JSON.parse(vm.runInContext('JSON.stringify(D35.forecastLatest(new Map(WEEKLY.districts[WEEKLY.lead]), new Map(WEEKLY.ref.series), 4))', box));
const expected = JSON.parse(src('out/results.json')).latest.h4;
assert.strictEqual(Math.round(f.point), expected.forecast, 'browser bundle and analysis disagree on the 4-week forecast');
assert.strictEqual(f.advice, expected.advice);
// Every district in the dropdown, at every look-ahead, must yield a forecast, a test result and a calendar without error.
const swept = vm.runInContext(`(function () {
  var R = new Map(WEEKLY.ref.series), n = 0;
  for (var name of Object.keys(WEEKLY.districts)) {
    var A = new Map(WEEKLY.districts[name]), lastA = Math.max.apply(null, Array.from(A.keys()));
    for (var h of [1, 2, 4]) {
      var f = D35.forecastLatest(A, R, h);
      if (f.noRecentPrice) f = D35.forecastLatest(A, new Map(Array.from(R).filter(function (e) { return e[0] <= lastA; })), h); // the page's fallback for a quiet district
      if (!(f.point > 0 && f.lo <= f.point && f.point <= f.hi)) throw new Error('bad forecast for ' + name + ' at ' + h + ' weeks');
      n++;
    }
    var bt = D35.backtest(A, R, { horizons: [1, 2, 4], testWeeks: 156, refitEvery: 26 });
    if (!(bt[1].n >= 0 && bt[4].n >= 0)) throw new Error('bad test result for ' + name);
    if (D35.seasonCalendar(A).length !== 12) throw new Error('bad calendar for ' + name);
  }
  return n;
})()`, box);
console.log(`docs/ built. Bundle check passed: 4-week forecast Rs ${Math.round(f.point)}; ${swept} district-and-horizon forecasts all valid.`);
